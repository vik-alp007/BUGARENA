import '@testing-library/jest-dom';

// Polyfill window.localStorage for Node 26 / jsdom test environment
const mockStorage = (() => {
  let store = {};
  return {
    getItem: (key) => store[key] || null,
    setItem: (key, value) => {
      store[key] = String(value);
    },
    removeItem: (key) => {
      delete store[key];
    },
    clear: () => {
      store = {};
    }
  };
})();

Object.defineProperty(window, 'localStorage', {
  value: mockStorage,
  writable: true
});

global.localStorage = mockStorage;

// Polyfill window.matchMedia if needed
Object.defineProperty(window, 'matchMedia', {
  writable: true,
  value: (query) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => {}
  })
});

// Polyfill scrollIntoView
Element.prototype.scrollIntoView = () => {};
